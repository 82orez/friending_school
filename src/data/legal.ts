export type LegalListItem =
  | string
  | {
      text: string;
      note?: string; // 번호 없는 부연 한 줄(예: 제10조 1항 서비스 목록)
      sub?: string[]; // 중첩 목록 1) 2) 3) …
    };

export type LegalBulletItem = string | { text: string; sub?: string[] };

export type LegalTable = { headers: string[]; rows: string[][] };

export type LegalBlock =
  | string // 문단
  | { list: LegalListItem[] } // 번호 목록(note/sub 지원)
  | { bullets: LegalBulletItem[] } // • 목록(연락처 블록 등)
  | { table: LegalTable }; // 표(예: 개인정보 처리 위탁)

export type LegalSection = {
  heading: string;
  blocks: LegalBlock[];
};

export type LegalDoc = {
  slug: "terms" | "privacy" | "refund";
  title: string;
  status: "ready" | "preparing";
  effectiveDate?: string;
  intro?: string; // 제1조 앞 머리말 문단
  sections?: LegalSection[];
};

